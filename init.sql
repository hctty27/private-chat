-- 私聊系统数据库初始化脚本（PostgreSQL）
--
-- 说明：
-- 1. 这里默认目标数据库已经由 docker-compose 的 POSTGRES_DB 创建完成。
-- 2. 如果你手动初始化，请先创建 private_chat 数据库，再执行本脚本。

-- 用户表
CREATE TABLE IF NOT EXISTS t_user (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50) NOT NULL UNIQUE,
    password   VARCHAR(128) NOT NULL,
    nickname   VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 关系表
CREATE TABLE IF NOT EXISTS t_relation (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    target_id  BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_relation UNIQUE (user_id, target_id)
);

CREATE INDEX IF NOT EXISTS idx_relation_user ON t_relation (user_id);

-- 文件元数据表。object_key 保存相对对象名；R2_OBJECT_PREFIX 由应用运行时拼接。
CREATE TABLE IF NOT EXISTS t_file (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_key            VARCHAR(512) NOT NULL,
    owner_id              BIGINT NOT NULL REFERENCES t_user(id),
    conversation_id       VARCHAR(64) NOT NULL,
    original_name         VARCHAR(255) NOT NULL,
    expected_size         BIGINT NOT NULL,
    actual_size           BIGINT,
    claimed_content_type  VARCHAR(128) NOT NULL DEFAULT 'application/octet-stream',
    detected_content_type VARCHAR(128),
    status                VARCHAR(16) NOT NULL DEFAULT 'pending',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    confirmed_at          TIMESTAMPTZ,
    CONSTRAINT uk_file_object_conversation UNIQUE (object_key, conversation_id),
    CONSTRAINT ck_file_expected_size CHECK (expected_size >= 0 AND expected_size <= 104857600),
    CONSTRAINT ck_file_actual_size CHECK (actual_size IS NULL OR (actual_size >= 0 AND actual_size <= 104857600)),
    CONSTRAINT ck_file_status CHECK (status IN ('pending', 'ready'))
);

CREATE INDEX IF NOT EXISTS idx_file_object_key
    ON t_file (object_key);

CREATE INDEX IF NOT EXISTS idx_file_owner_created
    ON t_file (owner_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_file_conversation_created
    ON t_file (conversation_id, created_at DESC);

-- 消息表
CREATE TABLE IF NOT EXISTS t_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(64) NOT NULL,
    sender_id       BIGINT NOT NULL,
    receiver_id     BIGINT NOT NULL,
    msg_type        SMALLINT NOT NULL,
    content         TEXT,
    file_id         BIGINT REFERENCES t_file(id),
    file_url        VARCHAR(512),
    file_name       VARCHAR(255),
    file_size       BIGINT,
    is_read         SMALLINT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_message_msg_type CHECK (msg_type IN (1, 2, 3, 4, 5)),
    CONSTRAINT ck_message_is_read CHECK (is_read IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_message_conversation
    ON t_message (conversation_id, created_at);

CREATE INDEX IF NOT EXISTS idx_message_receiver_unread
    ON t_message (receiver_id, is_read, created_at);

CREATE INDEX IF NOT EXISTS idx_message_conv_sender_receiver_read
    ON t_message (conversation_id, sender_id, receiver_id, is_read);

CREATE INDEX IF NOT EXISTS idx_message_file_id
    ON t_message (file_id) WHERE file_id IS NOT NULL;


BEGIN;

CREATE TABLE IF NOT EXISTS t_file (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_key            VARCHAR(512) NOT NULL,
    owner_id              BIGINT NOT NULL REFERENCES t_user(id),
    conversation_id       VARCHAR(64) NOT NULL,
    original_name         VARCHAR(255) NOT NULL,
    expected_size         BIGINT NOT NULL,
    actual_size           BIGINT,
    claimed_content_type  VARCHAR(128) NOT NULL DEFAULT 'application/octet-stream',
    detected_content_type VARCHAR(128),
    status                VARCHAR(16) NOT NULL DEFAULT 'pending',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    confirmed_at          TIMESTAMPTZ,
    CONSTRAINT uk_file_object_conversation UNIQUE (object_key, conversation_id),
    CONSTRAINT ck_file_expected_size CHECK (expected_size >= 0 AND expected_size <= 104857600),
    CONSTRAINT ck_file_actual_size CHECK (actual_size IS NULL OR (actual_size >= 0 AND actual_size <= 104857600)),
    CONSTRAINT ck_file_status CHECK (status IN ('pending', 'ready'))
);

CREATE INDEX IF NOT EXISTS idx_file_object_key ON t_file (object_key);
CREATE INDEX IF NOT EXISTS idx_file_owner_created ON t_file (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_file_conversation_created ON t_file (conversation_id, created_at DESC);

ALTER TABLE t_message ADD COLUMN IF NOT EXISTS file_id BIGINT;

-- Backfill legacy message URLs. `object_key` is the relative object name; the configured
-- R2_OBJECT_PREFIX is applied by the application at runtime. A legacy object may have
-- been re-used in more than one conversation, so create one authorization record per
-- object + conversation rather than silently breaking one conversation during migration.
INSERT INTO t_file (
    object_key,
    owner_id,
    conversation_id,
    original_name,
    expected_size,
    actual_size,
    claimed_content_type,
    detected_content_type,
    status,
    confirmed_at
)
SELECT DISTINCT ON (regexp_replace(m.file_url, '^.*/', ''), m.conversation_id)
    regexp_replace(m.file_url, '^.*/', ''),
    m.sender_id,
    m.conversation_id,
    COALESCE(NULLIF(m.file_name, ''), regexp_replace(m.file_url, '^.*/', '')),
    GREATEST(COALESCE(m.file_size, 0), 0),
    GREATEST(COALESCE(m.file_size, 0), 0),
    'application/octet-stream',
    NULL,
    'ready',
    m.created_at
FROM t_message m
WHERE m.file_url IS NOT NULL
  AND m.file_url LIKE '/api/file/download/%'
  AND regexp_replace(m.file_url, '^.*/', '') <> ''
ORDER BY regexp_replace(m.file_url, '^.*/', ''), m.conversation_id, m.id
ON CONFLICT (object_key, conversation_id) DO NOTHING;

UPDATE t_message m
SET file_id = f.id
FROM t_file f
WHERE m.file_id IS NULL
  AND m.file_url IS NOT NULL
  AND f.object_key = regexp_replace(m.file_url, '^.*/', '')
  AND f.conversation_id = m.conversation_id;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu
          ON tc.constraint_name = kcu.constraint_name
         AND tc.constraint_schema = kcu.constraint_schema
        JOIN information_schema.constraint_column_usage ccu
          ON tc.constraint_name = ccu.constraint_name
         AND tc.constraint_schema = ccu.constraint_schema
        WHERE tc.constraint_type = 'FOREIGN KEY'
          AND tc.table_schema = current_schema()
          AND tc.table_name = 't_message'
          AND kcu.column_name = 'file_id'
          AND ccu.table_schema = current_schema()
          AND ccu.table_name = 't_file'
          AND ccu.column_name = 'id'
    ) THEN
        ALTER TABLE t_message
            ADD CONSTRAINT fk_message_file FOREIGN KEY (file_id) REFERENCES t_file(id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_message_file_id ON t_message (file_id) WHERE file_id IS NOT NULL;

COMMIT;
